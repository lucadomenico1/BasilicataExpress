package model;

public class Comune {
	private int id;
	private String nome;
	
	//Costruttore
	public Comune() {


	}

	//Metodi getter e setter
	public int getId() {
		return id;
	}

	public void setId(int id) {
		this.id = id;
	}

	public String getNomeComune() {
		return nome;
	}

	public void setNomeComune(String nomeComune) {
		this.nome = nomeComune;
	}
	
	
	
	
}
